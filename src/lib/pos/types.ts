export type Role = "admin" | "manager" | "cashier" | "accountant";

export type Payment = "Cash" | "JazzCash" | "EasyPaisa" | "Card" | "Credit";

/** Physical/digital tender used to receive money. Independent of commercial payment status (Credit vs paid-in-full). */
export type TenderMethod = "Cash" | "Card" | "JazzCash" | "EasyPaisa";

export type HeldSale = {
  id: number;
  created_at: string;
  customer_id: number | null;
  payment: Payment;
  /** How money was actually received; defaults to Cash for legacy held sales. */
  tender_method?: TenderMethod;
  discount: number;
  paid: number;
  cart: CartLine[];
};

export type View =
  | "dashboard"
  | "pos"
  | "inventory"
  | "categories"
  | "customers"
  | "sales"
  | "expenses"
  | "settings";

export type User = { id: number; name: string; role: Role; pin?: string; pinHash?: string; pinSalt?: string };

export type Category = { id: number; name: string };

export type Product = {
  id: number;
  name: string;
  barcode: string | null;
  category_id: number;
  /** Integer minor units of the store currency. */
  cost: number;
  /** Integer minor units of the store currency. */
  selling: number;
  stock: number;
  min_stock: number;
  image: string | null;
};

export type Customer = {
  id: number;
  name: string;
  phone: string;
  address: string;
  /** Integer minor units owed by the customer. */
  balance: number;
};

export type SaleItem = {
  product_id: number;
  name: string;
  qty: number;
  price: number;
  cost: number;
};

export type Sale = {
  id: number;
  bill_id: string;
  created_at: string;
  customer_id: number | null;
  customer_name: string;
  /** Amount charged before tax when prices exclude tax; net of tax when prices include it. */
  net: number;
  /** Tax collected on this bill, minor units. Not revenue and not margin. */
  tax: number;
  tax_rate_bps: number;
  /** Net amount charged, minor units, including tax. */
  total: number;
  subtotal: number;
  discount: number;
  /** Amount the customer handed over, minor units. */
  paid: number;
  /** Cash returned. Only cash tenders produce change. */
  change: number;
  /** Cash added to the drawer by this sale, after change. */
  drawer_cash: number;
  /** Unpaid remainder added to the customer balance. */
  balance_due: number;
  payment: Payment;
  /**
   * How money was actually received for the paid portion.
   * Independent of `payment` (which may be Credit).
   * Legacy records without this field are treated as Cash when payment is Cash/Credit,
   * or as the payment method itself for Card/JazzCash/EasyPaisa.
   */
  tender_method: TenderMethod;
  /** Gross margin after the cart discount. Not operating profit. */
  gross_margin: number;
  items: SaleItem[];
};

export type Expense = {
  id: number;
  created_at: string;
  category: string;
  description: string;
  amount: number;
  /** When true, the amount left the cash drawer. */
  affects_cash: boolean;
};

export type Settings = {
  storeName: string;
  phone: string;
  address: string;
  currency: string;
  locale: string;
  timeZone: string;
  /** Display name, for example VAT or GST. Not a legal filing. */
  taxName: string;
  /** 1800 means 18.00%. Zero turns tax off. */
  taxRateBps: number;
  pricesIncludeTax: boolean;
  taxRegistration: string;
};

export type EndOfDay = {
  id: number;
  date: string;
  closed_at: string;
  closed_by: number;
  sales_total: number;
  /** Actual cash received into the drawer from sales (after change). */
  cash_sales: number;
  /** Card receipts, including card tenders against credit sales. */
  card_sales: number;
  /** JazzCash + EasyPaisa receipts, including digital tenders against credit sales. */
  digital_sales: number;
  /** Outstanding credit balances generated by sales that day (not amounts already received). */
  credit_sales: number;
  expenses_total: number;
  cash_expenses: number;
  /** Sum of sale gross margins minus every expense that day. Not operating profit. */
  margin_after_expenses: number;
  bills: number;
  cash_counted: number;
  cash_variance: number;
  notes: string;
};

/** Append-only amendment to a previously closed business day. Original EndOfDay is never mutated. */
export type DayAmendment = {
  id: number;
  end_of_day_id: number;
  date: string;
  amended_at: string;
  amended_by: number;
  cash_counted: number;
  notes: string;
};

export type StockMove = {
  id: number;
  created_at: string;
  product_id: number;
  product_name: string;
  delta: number;
  stock_after: number;
  reason: string;
  user_id: number;
};

export type CartLine = {
  product_id: number;
  qty: number;
  name: string;
  price: number;
  cost: number;
};

export type NextIds = {
  product: number;
  category: number;
  customer: number;
  sale: number;
  expense: number;
  end_of_day: number;
  held_sale: number;
  stock_move: number;
  day_amendment: number;
};

export const DATA_VERSION = 6;

export type PosDb = {
  version: number;
  users: User[];
  categories: Category[];
  products: Product[];
  customers: Customer[];
  sales: Sale[];
  expenses: Expense[];
  end_of_days: EndOfDay[];
  /** Append-only history of cash-count amendments to closed days. */
  day_amendments: DayAmendment[];
  stock_moves: StockMove[];
  settings: Settings;
  held_sales: HeldSale[];
  next: NextIds;
};

export const PAYMENTS: Payment[] = ["Cash", "JazzCash", "EasyPaisa", "Card", "Credit"];

export const TENDER_METHODS: TenderMethod[] = ["Cash", "Card", "JazzCash", "EasyPaisa"];

/** Conservative default for legacy sales that never recorded a tender method. */
export const DEFAULT_TENDER: TenderMethod = "Cash";

export const EXPENSE_CATEGORIES = [
  "Rent",
  "Utilities",
  "Salary",
  "Transport",
  "Supplies",
  "Other",
] as const;

export const ROLES: Role[] = ["admin", "manager", "cashier", "accountant"];
